/**
 * Generate js/supabase-env.js for Cloudflare (and local) builds.
 *
 * Reads publishable browser config only:
 *   SUPABASE_URL        (required)
 *   SUPABASE_ANON_KEY   (required) — publishable/anon key only
 *   PULSE_SITE_URL      (optional) — Auth redirect base; empty → window.location.origin
 *
 * Never accepts or writes a service-role key.
 * Output is gitignored; run before `npx wrangler deploy`.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const OUT_FILE = join(ROOT, 'js', 'supabase-env.js');

const PLACEHOLDER_PATTERNS = [
  /^$/i,
  /replace_with/i,
  /your[-_]?publishable/i,
  /your[-_]?anon/i,
  /changeme/i,
  /example\.com/i,
  /placeholder/i,
  /todo/i,
  /xxx+/i
];

function fail(message) {
  console.error(`[generate-supabase-env] ${message}`);
  process.exit(1);
}

function readRequired(name) {
  const raw = process.env[name];
  if (raw === undefined || raw === null) {
    fail(`Missing required environment variable: ${name}`);
  }
  const value = String(raw).trim();
  if (!value) {
    fail(`Environment variable ${name} is empty.`);
  }
  for (const pattern of PLACEHOLDER_PATTERNS) {
    if (pattern.test(value)) {
      fail(`Environment variable ${name} looks like a placeholder. Set a real value.`);
    }
  }
  return value;
}

function readOptionalSiteUrl() {
  const raw = process.env.PULSE_SITE_URL;
  if (raw === undefined || raw === null) return '';
  const value = String(raw).trim().replace(/\/$/, '');
  if (!value) return '';
  for (const pattern of PLACEHOLDER_PATTERNS) {
    if (pattern.test(value)) {
      fail('PULSE_SITE_URL looks like a placeholder. Set a real URL or omit it.');
    }
  }
  if (!/^https:\/\//i.test(value)) {
    fail('PULSE_SITE_URL must be an https:// URL when set.');
  }
  return value;
}

function assertNoServiceRole(anonKey) {
  // Defense in depth: never write anything that looks like a service-role JWT claim.
  let payload = '';
  try {
    const parts = anonKey.split('.');
    if (parts.length >= 2) {
      payload = Buffer.from(parts[1], 'base64url').toString('utf8');
    }
  } catch {
    /* non-JWT keys still allowed if clearly anon/publishable naming upstream */
  }
  if (/service_role/i.test(anonKey) || /"role"\s*:\s*"service_role"/i.test(payload)) {
    fail('Refusing to write a Supabase service-role key. Use the publishable/anon key only.');
  }
  if (process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.SERVICE_ROLE_KEY) {
    fail(
      'SUPABASE_SERVICE_ROLE_KEY / SERVICE_ROLE_KEY must not be used with this script. Remove them from the build environment for this step.'
    );
  }
}

function assertSupabaseUrl(url) {
  let parsed;
  try {
    parsed = new URL(url);
  } catch {
    fail('SUPABASE_URL must be a valid URL.');
  }
  if (parsed.protocol !== 'https:') {
    fail('SUPABASE_URL must use https://');
  }
  if (!/\.supabase\.co$/i.test(parsed.hostname) && !/\.supabase\.in$/i.test(parsed.hostname)) {
    // Allow custom domains later; still require https + non-placeholder (already checked).
    console.warn(
      '[generate-supabase-env] SUPABASE_URL host is not *.supabase.co — continuing (custom domain?).'
    );
  }
}

function escapeForSingleQuotedJs(value) {
  return value
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
}

const url = readRequired('SUPABASE_URL');
const anonKey = readRequired('SUPABASE_ANON_KEY');
const siteUrl = readOptionalSiteUrl();

assertSupabaseUrl(url);
assertNoServiceRole(anonKey);

const contents = `/**
 * Generated by scripts/generate-supabase-env.mjs — do not commit.
 * Publishable anon key only. Never the service-role key.
 */
window.PULSE_SUPABASE = {
  url: '${escapeForSingleQuotedJs(url)}',
  anonKey: '${escapeForSingleQuotedJs(anonKey)}',
  siteUrl: '${escapeForSingleQuotedJs(siteUrl)}'
};
`;

mkdirSync(dirname(OUT_FILE), { recursive: true });
writeFileSync(OUT_FILE, contents, 'utf8');
console.log(`[generate-supabase-env] Wrote ${OUT_FILE.replace(/\\/g, '/')}`);
